import type { WorkspaceLanguage } from "./state/useWorkspacePreferences";
import { workspaceInterfaceMessages } from "./locale/workspaceInterfaceMessages";

const formatMessage = (
  template: string,
  values: Record<string, string | number>,
) => Object.entries(values).reduce(
  (result, [key, value]) => result.split(`{{${key}}}`).join(String(value)),
  template,
);

export type WorkspaceInterfaceCopy = ReturnType<typeof getWorkspaceInterfaceCopy>;

export const getWorkspaceInterfaceCopy = (language: WorkspaceLanguage) => {
  const copy = workspaceInterfaceMessages[language];
  const format = (template: string, values: Record<string, string | number>) =>
    formatMessage(template, values);

  return {
    tabs: {
      scrollLeft: copy.tabsScrollLeft,
      openDocuments: copy.tabsOpenDocuments,
      renameDocument: (name: string) => format(copy.tabsRenameDocument, { name }),
      collaboratorsInDocument: (names: string) => format(copy.tabsCollaboratorsInDocument, { names }),
      closeDocument: (name: string) => format(copy.tabsCloseDocument, { name }),
      close: copy.tabsClose,
      closeAll: copy.tabsCloseAll,
      closeOthers: copy.tabsCloseOthers,
      manage: copy.tabsManage,
      newDocument: copy.tabsNewDocument,
      reopenLastClosed: copy.tabsReopenLastClosed,
      scrollRight: copy.tabsScrollRight,
    },
    sidePanel: {
      dismiss: copy.panelDismiss,
      label: copy.panelLabel,
      sections: copy.panelSections,
      resize: copy.panelResize,
      tabs: {
        files: copy.panelFiles,
        outline: copy.panelOutline,
        links: copy.panelLinks,
        graph: copy.panelGraph,
        comments: copy.panelComments,
        search: copy.panelSearch,
        knowledge: copy.panelKnowledge,
        libraries: copy.panelLibraries,
      },
      knowledge: {
        label: copy.panelKnowledge,
        description: copy.panelKnowledgeDescription,
        summary: (concepts: number, documents: number) =>
          format(copy.panelKnowledgeSummary, { concepts, documents }),
        empty: copy.panelKnowledgeEmpty,
        back: copy.panelKnowledgeBack,
        explore: copy.panelKnowledgeExplore,
        review: copy.panelKnowledgeReview,
        concepts: copy.graphConcepts,
        searchPlaceholder: copy.panelKnowledgeSearchPlaceholder,
        filters: copy.searchFilters,
        addFilter: copy.panelKnowledgeAddFilter,
        chooseField: copy.panelKnowledgeChooseField,
        suggestedFields: copy.panelKnowledgeSuggestedFields,
        allFields: copy.panelKnowledgeAllFields,
        backToFields: copy.panelKnowledgeBackToFields,
        closeFilters: copy.panelKnowledgeCloseFilters,
        applyFilters: copy.panelKnowledgeApplyFilters,
        noFilterFields: copy.panelKnowledgeNoFilterFields,
        emptyValue: copy.panelKnowledgeEmptyValue,
        contains: copy.panelKnowledgeContains,
        equals: copy.panelKnowledgeEquals,
        on: copy.panelKnowledgeOn,
        before: copy.panelKnowledgeBefore,
        after: copy.panelKnowledgeAfter,
        atLeast: copy.panelKnowledgeAtLeast,
        atMost: copy.panelKnowledgeAtMost,
        trueValue: copy.panelKnowledgeTrue,
        falseValue: copy.panelKnowledgeFalse,
        enterValue: copy.panelKnowledgeEnterValue,
        clearFilters: copy.searchClearFilters,
        removeFilter: (name: string) => format(copy.searchRemoveFilter, { name }),
        types: copy.searchTypes,
        tags: copy.searchTags,
        metadata: copy.panelKnowledgeMetadata,
        connections: copy.panelKnowledgeConnections,
        reviewLoading: copy.panelKnowledgeReviewLoading,
        reviewHealthy: copy.panelKnowledgeReviewHealthy,
        reviewFreshness: copy.panelKnowledgeReviewFreshness,
        reviewTrust: copy.panelKnowledgeReviewTrust,
        reviewLinks: copy.panelKnowledgeReviewLinks,
        reviewSources: copy.panelKnowledgeReviewSources,
        reviewMetadata: copy.panelKnowledgeReviewMetadata,
        reviewStructure: copy.panelKnowledgeReviewStructure,
        valueCount: (count: number) => format(copy.panelKnowledgeValueCount, { count }),
        findingCount: (count: number) => String(count),
        connectionCount: (count: number) =>
          format(copy.panelKnowledgeConnectionCount, { count }),
        filteredEmpty: copy.panelKnowledgeFilteredEmpty,
        noConcepts: copy.panelKnowledgeNoDocuments,
        documentCount: (count: number) => count === 1
          ? copy.searchOneDocument
          : format(copy.searchDocuments, { count }),
      },
      checks: {
        label: copy.panelChecks,
        loading: copy.panelChecksLoading,
        healthy: copy.panelChecksHealthy,
        attention: copy.panelChecksAttention,
        freshness: copy.panelChecksFreshness,
        trust: copy.panelChecksTrust,
        links: copy.panelChecksLinks,
        sources: copy.panelChecksSources,
        metadata: copy.panelChecksMetadata,
        structure: copy.panelChecksStructure,
      },
      libraries: {
        label: copy.panelLibraries,
        description: copy.panelLibrariesDescription,
        empty: copy.panelLibrariesEmpty,
      },
      noDocumentOpen: copy.panelNoDocumentOpen,
      search: {
        placeholder: copy.searchPlaceholder,
        settings: copy.searchSettings,
        filters: copy.searchFilters,
        backToResults: copy.searchBackToResults,
        noMatches: copy.searchNoMatches,
        noDocuments: copy.searchNoDocuments,
        results: copy.searchResults,
        types: copy.searchTypes,
        tags: copy.searchTags,
        clearFilters: copy.searchClearFilters,
        chooseFilters: copy.searchChooseFilters,
        showDocuments: (count: number) => count === 1
          ? copy.searchShowOneDocument
          : format(copy.searchShowDocuments, { count }),
        documentCount: (count: number) => count === 1
          ? copy.searchOneDocument
          : format(copy.searchDocuments, { count }),
        typeFilter: (name: string) => format(copy.searchTypeFilter, { name }),
        tagFilter: (name: string) => format(copy.searchTagFilter, { name }),
        removeFilter: (name: string) => format(copy.searchRemoveFilter, { name }),
        openResource: (name: string) => format(copy.searchOpenResource, { name }),
        noFacetValues: copy.searchNoFacetValues,
        views: copy.searchViews,
        listView: copy.searchListView,
        mapView: copy.searchMapView,
        label: copy.searchLabel,
        reviewView: copy.searchReviewView,
        browseView: copy.searchBrowseView,
        noConcepts: copy.searchNoConcepts,
        conceptCount: (count: number) => count === 1
          ? copy.searchOneConcept
          : format(copy.searchConcepts, { count }),
        untyped: copy.searchUntyped,
      },
      files: {
        sharedWorkspace: copy.filesSharedWorkspace,
        currentDocument: copy.panelFiles,
        renameFolder: (name: string) => format(copy.filesRenameFolder, { name }),
        moreActions: (name: string) => format(copy.filesMoreActions, { name }),
        actions: (name: string) => format(copy.filesActions, { name }),
        rename: copy.filesRename,
        delete: copy.filesDelete,
        renameInPanel: (name: string) => format(copy.filesRenameInPanel, { name }),
        open: (name: string) => format(copy.filesOpen, { name }),
        sharedInRoom: copy.filesSharedInRoom,
        localDocument: copy.filesLocalDocument,
        duplicate: copy.filesDuplicate,
        copyMarkdown: copy.filesCopyMarkdown,
        collapseAll: copy.filesCollapseAll,
        expandAll: copy.filesExpandAll,
        openMarkdown: copy.filesOpenMarkdown,
        create: copy.filesCreate,
        createInWorkspace: copy.filesCreateInWorkspace,
        newDocument: copy.filesNewDocument,
        newFolder: copy.filesNewFolder,
        tree: copy.filesTree,
        noneFound: copy.panelNoDocuments,
      },
      outline: {
        forFile: (name: string) => format(copy.outlineFor, { name }),
        expand: copy.outlineExpand,
        collapse: copy.outlineCollapse,
        expandAll: copy.outlineExpandAll,
        collapseAll: copy.outlineCollapseAll,
        none: copy.outlineNone,
      },
      links: {
        forFile: (name: string) => format(copy.linksFor, { name }),
        outgoing: copy.linksOutgoing,
        backlinks: copy.linksBacklinks,
        outgoingNone: copy.linksOutgoingNone,
        backlinksNone: copy.linksBacklinksNone,
        unavailable: copy.linksUnavailable,
        open: (name: string) => format(copy.linksOpen, { name }),
        openExternal: (name: string) => format(copy.linksOpenExternal, { name }),
        goToBroken: (name: string) => format(copy.linksGoToBroken, { name }),
        chooseAmbiguous: (count: number, name: string) =>
          format(copy.linksChooseAmbiguous, { count, name }),
        resolveWith: (name: string) => format(copy.linksResolveWith, { name }),
        notFound: copy.linksNotFound,
        matchCount: (count: number) => format(copy.linksMatchCount, { count }),
        expandSection: (name: string) => format(copy.linksExpandSection, { name }),
        collapseSection: (name: string) => format(copy.linksCollapseSection, { name }),
        openMap: copy.linksOpenMap,
      },
      graph: {
        forFile: (name: string) => format(copy.graphFor, { name }),
        title: copy.graphTitle,
        description: copy.graphDescription,
        close: copy.graphClose,
        summary: (documents: number, links: number) =>
          format(
            documents === 1 ? copy.graphSummaryOne : copy.graphSummary,
            { documents, links },
          ),
        conceptSummary: (documents: number, links: number) =>
          format(
            documents === 1
              ? copy.graphConceptSummaryOne
              : copy.graphConceptSummary,
            { documents, links },
          ),
        none: copy.graphNone,
        unavailable: copy.graphUnavailable,
        open: (name: string) => format(copy.graphOpen, { name }),
        current: (name: string) => format(copy.graphCurrent, { name }),
        truncated: (visible: number, total: number) =>
          format(copy.graphTruncated, { visible, total }),
        scope: copy.graphScope,
        local: copy.graphLocal,
        workspace: copy.graphWorkspace,
        concepts: copy.graphConcepts,
        filters: copy.graphFilters,
        types: copy.graphTypes,
        tags: copy.graphTags,
        clearFilters: copy.graphClearFilters,
        noConcepts: copy.graphNoConcepts,
        roles: {
          concept: copy.graphConceptRole,
          index: copy.graphIndexRole,
          log: copy.graphLogRole,
        },
        openResource: copy.graphOpenResource,
      },
      comments: {
        title: copy.commentsTitle,
        all: copy.commentsAll,
        currentFile: copy.commentsCurrentFile,
        showCurrent: copy.commentsShowCurrent,
        showAll: copy.commentsShowAll,
        none: copy.commentsNone,
        emptyHint: copy.commentsEmptyHint,
        as: copy.commentsAs,
        authorName: copy.commentsAuthorName,
        selectedPlaceholder: copy.commentsSelectedPlaceholder,
        filePlaceholder: copy.commentsFilePlaceholder,
        addTo: (name: string) => format(copy.commentsAddTo, { name }),
        selected: (text: string) => format(copy.commentsSelected, { text }),
        selectedCharacters: (count: number) => format(
          count === 1 ? copy.commentsSelectedCharacter : copy.commentsSelectedCharacters,
          { count },
        ),
        cancel: copy.commentsCancel,
        comment: copy.commentsComment,
        reply: copy.commentsReply,
        replyLabel: (count: number) => `${count} ${count === 1 ? copy.commentsReply : copy.commentsReplies}`,
        showReplies: (label: string) => format(copy.commentsShowReplies, { label }),
        hideReplies: (label: string) => format(copy.commentsHideReplies, { label }),
        guest: copy.commentsGuest,
        untitled: copy.commentsUntitled,
        actions: copy.commentsActions,
        replyAction: copy.commentsReplyAction,
        reopen: copy.commentsReopen,
        resolve: copy.commentsResolve,
        moreActions: (name: string) => format(copy.commentsMoreActions, { name }),
        menuActions: (name: string) => format(copy.commentsMenuActions, { name }),
        delete: copy.filesDelete,
        showQuote: copy.commentsShowQuote,
        resolved: (count: number) => format(copy.commentsResolved, { count }),
        resolvedLabel: copy.commentsResolvedLabel,
        hideResolved: copy.commentsHideResolved,
        showResolved: copy.commentsShowResolved,
      },
    },
  };
};
